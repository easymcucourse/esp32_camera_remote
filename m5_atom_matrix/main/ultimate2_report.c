bool ultimate2_map_matches(const uint8_t *map, size_t size)
{ return map && size==sizeof(ultimate2_report_map) && !memcmp(map,ultimate2_report_map,size); }
bool ultimate2_parse_report(const uint8_t *p, size_t size, ds4_state_t *out)
{
    /* HOGP characteristic data omits report ID. This map has exactly one
     * Input report: ID 1, 264 bits. ID 5 is Output only. */
    if (!p || !out || size!=33) return false;
    unsigned hat=p[0]&15;
    if (hat>7 && hat!=15) return false;
    uint32_t buttons=0;
    if (hat==0 || hat==1 || hat==7) buttons|=1u<<4;
    if (hat==1 || hat==2 || hat==3) buttons|=1u<<5;
    if (hat==3 || hat==4 || hat==5) buttons|=1u<<6;
    if (hat==5 || hat==6 || hat==7) buttons|=1u<<7;
    uint32_t raw=p[7]|((uint32_t)p[8]<<8)|((uint32_t)p[9]<<16);
    /* Android/Nintendo letter layout: B,A,unused,Y,X,unused,LB,RB,
     * LT,RT,select,start,home,L3,R3. Physical letters need hardware acceptance. */
    static const int8_t canonical[15]={13,14,-1,12,15,-1,10,11,8,9,0,3,16,1,2};
    for (unsigned i=0;i<15;++i)
        if (canonical[i]>=0 && (raw&(1u<<i))) buttons|=1u<<canonical[i];
    *out=(ds4_state_t){.connected=true,.buttons=buttons,.battery=255,
        .lx=(int)p[1]-128,.ly=(int)p[2]-128,.rx=(int)p[3]-128,.ry=(int)p[4]-128,
        .r2=p[5],.l2=p[6]};
    return true;
}
